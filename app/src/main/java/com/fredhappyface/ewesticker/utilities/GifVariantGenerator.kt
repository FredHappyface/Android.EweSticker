package com.fredhappyface.ewesticker.utilities

import android.content.Context
import android.os.Handler
import android.os.Looper
import com.elvishew.xlog.XLog
import com.fredhappyface.ewesticker.R
import com.google.android.material.progressindicator.LinearProgressIndicator
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.async
import kotlinx.coroutines.awaitAll
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.withContext
import java.io.File
import java.io.IOException
import java.util.concurrent.atomic.AtomicInteger

/**
 * Longest edge of a generated GIF. Matching tools/gif-variants.py keeps on-device output the same
 * size as a desktop conversion; at full 512 a typical animated sticker is over 4MB, which is too
 * heavy to send in a chat.
 */
private const val MAX_EDGE = 320

/** Palette entries per frame, again matching the reference implementation */
private const val COLORS = 128

/**
 * Generates GIF copies of animated webp stickers, on device.
 *
 * WhatsApp takes an animated webp directly as a sticker, but apps like Teams advertise image/gif and
 * nothing else, so a GIF is the only way an animated sticker keeps moving there. This produces those
 * copies during import, into the variants tree that StickerSender looks in, so nothing has to be
 * converted on a desktop first.
 *
 * Stickers that already have a variant are left alone, which means a GIF generated by
 * tools/gif-variants.py and imported alongside its webp is used as-is rather than redone.
 *
 * @property progressBar LinearProgressIndicator? updated as stickers are converted
 */
class GifVariantGenerator(
	private val context: Context,
	private val toaster: Toaster,
	private val progressBar: LinearProgressIndicator?,
) {
	private val mainHandler = Handler(Looper.getMainLooper())

	/**
	 * Convert every animated sticker that has no variant yet.
	 *
	 * @param stickersDir File the imported stickers tree
	 * @param variantsDir File the tree to write GIFs into
	 * @return Int how many GIFs were written
	 */
	/**
	 * @property pending Int how many stickers needed a variant
	 * @property written Int how many were produced; a shortfall means conversions failed
	 */
	data class Result(val pending: Int, val written: Int)

	suspend fun generate(stickersDir: File, variantsDir: File): Result {
		val pending = stickersDir.listFiles()
			?.filter { it.isDirectory }
			?.flatMap { pack ->
				pack.listFiles()
					?.filter { it.isFile && WebpAnimation.isAnimated(it) }
					?.map { pack.name to it }
					?: emptyList()
			}
			?.filterNot { (pack, sticker) ->
				File(variantsDir, "$pack/${sticker.nameWithoutExtension}.gif").isFile
			}
			?: emptyList()

		if (pending.isEmpty()) {
			XLog.i("No animated stickers are missing a GIF variant")
			return Result(0, 0)
		}

		XLog.i("Generating GIF variants for ${pending.size} animated sticker(s)...")
		withContext(Dispatchers.Main) {
			// Converting takes appreciably longer than the copy that precedes it, so say why the
			// import has not finished yet rather than appearing to hang.
			toaster.toast(context.getString(R.string.imported_035, pending.size))
			progressBar?.isIndeterminate = false
			progressBar?.progress = 0
		}

		val done = AtomicInteger()
		val written = AtomicInteger()
		// Dispatchers.Default is already sized to the number of cores, so this saturates the CPU
		// without oversubscribing it. Conversion is pure computation, so that is what we want.
		coroutineScope {
			pending.map { (pack, sticker) ->
				async(Dispatchers.Default) {
					val destination = File(variantsDir, "$pack/${sticker.nameWithoutExtension}.gif")
					if (convert(sticker, destination)) {
						written.incrementAndGet()
					}
					val finished = done.incrementAndGet()
					mainHandler.post {
						progressBar?.progress = finished * 100 / pending.size
					}
				}
			}.awaitAll()
		}

		XLog.i("Wrote ${written.get()} / ${pending.size} GIF variant(s)")
		return Result(pending.size, written.get())
	}

	/**
	 * Convert one animated webp to a GIF. Writes to a temporary file first so that a conversion
	 * interrupted part way through cannot leave behind a truncated GIF that later runs would mistake
	 * for finished work.
	 *
	 * @param source File the animated webp
	 * @param destination File the GIF to write
	 * @return Boolean true if a GIF was written
	 */
	internal fun convert(source: File, destination: File): Boolean {
		val animation = WebpAnimation.read(source) ?: return false
		val scale = minOf(1f, MAX_EDGE.toFloat() / maxOf(animation.width, animation.height))
		val outWidth = maxOf(1, (animation.width * scale).toInt())
		val outHeight = maxOf(1, (animation.height * scale).toInt())

		val durations = animation.durationsMs
		var complete = false
		var partial: File? = null
		try {
			destination.parentFile?.mkdirs()
			// A fixed ".part" name is not safe once conversions can also be started on demand from
			// the keyboard: two of them for the same sticker would open the same path, and the second
			// open truncates what the first has already written. Created inside the try because the
			// parent directory can vanish under us -- an import or a delete running concurrently --
			// and that must cost this sticker, not the whole batch.
			// A fixed prefix, because createTempFile rejects one shorter than three characters.
			partial = File.createTempFile("variant-", ".part", destination.parentFile)
			partial.outputStream().buffered().use { stream ->
				val encoder = GifEncoder(stream, outWidth, outHeight, COLORS)
				val pixels = IntArray(animation.width * animation.height)
				complete = animation.forEachFrame { index, bitmap ->
					bitmap.getPixels(pixels, 0, animation.width, 0, 0, animation.width, animation.height)
					val frame = if (scale < 1f) {
						ImageResampler.resize(
							pixels,
							animation.width,
							animation.height,
							outWidth,
							outHeight,
						)
					} else {
						pixels
					}
					encoder.addFrame(frame, durations.getOrElse(index) { 100 })
				}
				encoder.finish()
			}
			if (!complete) {
				XLog.e("Gave up converting '${source.name}', some frames would not decode")
				return false
			}
			if (!partial.renameTo(destination)) {
				XLog.e("Could not move the finished GIF into place for '${source.name}'")
				return false
			}
			XLog.i(
				"Converted '${source.name}' to ${animation.frameCount} GIF frames " +
					"(${destination.length() / 1024}KB)",
			)
			return true
		} catch (e: IOException) {
			XLog.e("Failed to convert '${source.name}' to a GIF")
			XLog.e(e)
			return false
		} catch (e: Throwable) {
			// One malformed sticker should cost us that sticker, not the whole batch. A bad webp
			// header can produce a negative array size or an oversized bitmap, neither of which is
			// an IOException, and these run as children of a scope that cancels on an escape.
			XLog.e("Failed to convert '${source.name}'")
			XLog.e(e)
			return false
		} finally {
			if (!complete) {
				partial?.delete()
			}
		}
	}
}
